/* map3d/export.js — real chart of a bot run for the 3D drafts. node design/map3d/export.js [seed=11] [years=600] [bot=rush] [out=data.js]
   Writes design/map3d/data.js (window.MAP={...}). Positions use ui.js layoutPos (ellipse 1.32 × 0.90, push apart at 28). */
const path=require('path'), fs=require('fs');
const sim=require(path.join(__dirname,'../../tools/sim.js'));
const C=sim.load(path.join(__dirname,'../../work/core.js'));
const [seed=11,years=600,bot='rush',outName='data.js']=process.argv.slice(2);   // E (v2) reads data-e.js: bank 5, year 2800 — a run with a real hub
let G; sim.play(C,+seed,+years,bot,g=>{G=g});
const P=C.PLANETS, S=C.SECTORS, CX=500, CY=350;
const Ls=P.map(q=>{ const R=S[q.sec].r; return {id:q.id,x:CX+Math.cos(q.ang)*R*1.32,y:CY+Math.sin(q.ang)*R*0.90} });
for(let it=0;it<40;it++){ let moved=false;
  for(let i=0;i<Ls.length;i++) for(let j=i+1;j<Ls.length;j++){ const a=Ls[i], b=Ls[j], dx=b.x-a.x, dy=b.y-a.y, d=Math.hypot(dx,dy)||0.01;
    if(d<28){ const k=(28-d)/2/d; a.x-=dx*k; a.y-=dy*k; b.x+=dx*k; b.y+=dy*k; moved=true } }
  if(!moved) break }
const XY={}; Ls.forEach(o=>XY[o.id]=o);
const worlds=P.map(p=>{ const c=G.colonies[p.id]; return {id:p.id,name:p.name,sec:p.sec,kind:p.kind,ang:+p.ang.toFixed(4),dist:p.dist,
  x:+XY[p.id].x.toFixed(1),y:+XY[p.id].y.toFixed(1),on:!!c,hub:!!(c&&c.hub),pop:c?Math.round(c.pop):0,
  ghost:!!(G.ghost&&G.ghost[p.id]),line:c?C.lineTo(G,p.id):null} });
const ships=G.ships.filter(s=>s.mode==='transit').map(s=>({cls:C.HULLS[s.hull].key,from:s.origin,to:s.dest||s.target,f:s.total?+(1-s.t/s.total).toFixed(3):0}));
const out={seed:+seed,year:G.day,bot,sectors:S.map((s,i)=>({name:s.name,r:s.r})),worlds,ships};
fs.writeFileSync(path.join(__dirname,outName),'/* generated by export.js — seed '+seed+', '+bot+' bot, year '+G.day+' */\nwindow.MAP='+JSON.stringify(out)+';\n');
console.log('sectors',S.length,'worlds',worlds.length,'on',worlds.filter(w=>w.on).length,'hubs',worlds.filter(w=>w.hub).length,'ships in transit',ships.length,'year',G.day,'over',G.over||'-');
