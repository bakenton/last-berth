/* LAST BERTH — шрифты нового интерфейса (Jost + Geist Mono, решение Никиты 14.10) вшиваются в страницу base64.
   node tools/fonts-embed.js   → work/web/fonts.css (только латиница и кириллица; файл в git, сеть нужна только этому скрипту)
   Google Fonts отдаёт woff2 браузерам с современным User-Agent. Jost — переменный шрифт: несколько весов могут
   ссылаться на один файл, такой файл вшивается один раз (одна @font-face с диапазоном весов). */
const fs=require('fs'), path=require('path');
const OUT=path.join(__dirname,'..','work','web','fonts.css');
const URL='https://fonts.googleapis.com/css2?family=Jost:wght@400;500;600;700&family=Geist+Mono:wght@400;600&display=swap';
const UA='Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const KEEP=['latin','cyrillic'];
(async()=>{
  const css=await (await fetch(URL,{headers:{'user-agent':UA}})).text();
  const blocks=[...css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face\s*\{([^}]*)\}/g)].filter(m=>KEEP.includes(m[1]));
  const byUrl=new Map();
  for(const m of blocks){
    const body=m[2], fam=body.match(/font-family:\s*'([^']+)'/)[1], w=+body.match(/font-weight:\s*(\d+)/)[1];
    const url=body.match(/url\((https:[^)]+)\)/)[1], range=body.match(/unicode-range:\s*([^;]+);/)[1];
    const k=fam+'|'+url; if(!byUrl.has(k)) byUrl.set(k,{fam,url,range,w:[]}); byUrl.get(k).w.push(w);
  }
  let out='/* generated by tools/fonts-embed.js — Jost + Geist Mono, latin + cyrillic, SIL Open Font License */\n', bytes=0;
  for(const f of byUrl.values()){
    const buf=Buffer.from(await (await fetch(f.url,{headers:{'user-agent':UA}})).arrayBuffer()); bytes+=buf.length;
    const lo=Math.min(...f.w), hi=Math.max(...f.w);
    out+="@font-face{font-family:'"+f.fam+"';font-style:normal;font-weight:"+(lo===hi?lo:lo+' '+hi)+";font-display:block;src:url(data:font/woff2;base64,"+buf.toString('base64')+") format('woff2');unicode-range:"+f.range+"}\n";
  }
  fs.mkdirSync(path.dirname(OUT),{recursive:true}); fs.writeFileSync(OUT,out);
  console.log('fonts.css:',byUrl.size,'files,',Math.round(bytes/1024),'KB woff2 →',Math.round(out.length/1024),'KB css');
})().catch(e=>{ console.error(e); process.exit(1) });
