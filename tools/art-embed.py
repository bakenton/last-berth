#   py -3 tools/art-embed.py   → work/web/art.css (файл в git; build.py вставляет его в <style>)
# Портрет Александры (плейсхолдер, решение Никиты 15.10): квадратная обрезка верхних 60 % кадра, 160×160.
# Кадры вступления N-01 (design/intro-1…4.webp, старый лор) убраны в v4.40: их место занял терминал главного меню.
import base64, io, os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, 'design')
OUT = os.path.join(ROOT, 'work', 'web', 'art.css')

def b64(data):
    return base64.b64encode(data).decode('ascii')

im = Image.open(os.path.join(D, 'alexandra-placeholder.webp')).convert('RGB')
w, h = im.size
side = min(w, round(h * 0.6))
x0 = (w - side) // 2
ava = im.crop((x0, 0, x0 + side, side)).resize((160, 160), Image.LANCZOS)
buf = io.BytesIO(); ava.save(buf, 'WEBP', quality=86, method=6)
out = ['/* generated by tools/art-embed.py — Alexandra (placeholder, local ComfyUI) */',
       '.ava{background:#202024 url(data:image/webp;base64,' + b64(buf.getvalue()) + ') center/cover no-repeat}']
total = len(buf.getvalue())
with open(OUT, 'w', encoding='utf-8', newline='') as f:
    f.write('\n'.join(out) + '\n')
print('art.css:', round(total / 1024), 'KB webp ->', round(os.path.getsize(OUT) / 1024), 'KB css')
